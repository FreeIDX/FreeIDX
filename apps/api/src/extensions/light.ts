/** 标签样式白名单（对齐 idx_tag 的 badge-* 取值，缺省 primary） */
const TAG_STYLES = [
  'primary',
  'secondary',
  'success',
  'danger',
  'warning',
  'info',
  'dark',
  'light',
];

/** 多行文本 → 结构数组：每行按 | 切段（trim），空行与字段不足的行丢弃 */
function lines(text: unknown): string[][] {
  return String(text ?? '')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => l.split('|').map((s) => s.trim()));
}

function parseSlides(config: Record<string, unknown>): LightSlide[] {
  const out: LightSlide[] = [];
  for (const p of lines(config.slides)) {
    const [name = '', url = '', pic = ''] = p;
    if (pic) out.push({ name, url, pic });
    if (out.length >= 8) break;
  }
  return out;
}

function parseLinks(config: Record<string, unknown>): LightLink[] {
  const out: LightLink[] = [];
  for (const p of lines(config.links)) {
    const [name = '', url = ''] = p;
    if (name && url) out.push({ name, url });
    if (out.length >= 20) break;
  }
  return out;
}

function parseTags(config: Record<string, unknown>): LightTag[] {
  const out: LightTag[] = [];
  for (const p of lines(config.tags)) {
    const name = (p[0] ?? '').slice(0, 12);
    if (!name) continue;
    const style = p[1];
    out.push({ name, style: style && TAG_STYLES.includes(style) ? style : 'primary' });
    if (out.length >= 30) break;
  }
  return out;
}

/** 开关语义：默认开（defaultOn），显式写入 0 才关 */
const on = (v: unknown, defaultOn: boolean): boolean =>
  v === undefined || v === '' ? defaultOn : Number(v) === 1;

/** 文本配置：去首尾空白（保留内部换行，供页脚/公告多行文案） */
const txt = (v: unknown): string => String(v ?? '').trim();

/** 配置 → 载荷（缺省即「出厂演示形态」：发现页/底栏/回顶/排行卡开，字体默认、暗色开） */
export function parseLightConfig(config: Record<string, unknown>): LightPayload {
  const styleN = Number(config.thread_list_style);
  const fontN = Number(config.body_font_style);
  const picN = Number(config.thread_summary_pic);
  const hour = (v: unknown, dft: number): number => {
    const n = Math.floor(Number(v));
    return Number.isFinite(n) && n >= 0 && n <= 23 ? n : dft;
  };
  return {
    enabled: true,
    discPage: on(config.disc_page, true),
    slides: parseSlides(config),
    links: parseLinks(config),
    tags: parseTags(config),
    preNextThread: on(config.pre_next_thread, false),
    summaryPic: picN === 6 || picN === 9 ? picN : 3,
    dockSwitch: on(config.dock_switch, true),
    showAllReply: on(config.show_all_reply, true),
    backTop: on(config.back_top, true),
    threadListStyle: styleN === 2 || styleN === 3 ? (styleN as 2 | 3) : 1,
    threadSummary: on(config.thread_summary, true),
    summaryWord:
      config.thread_summary_word === undefined || config.thread_summary_word === ''
        ? 100
        : Math.min(500, Math.max(0, Math.floor(Number(config.thread_summary_word)) || 0)),
    threadForumName: on(config.thread_forum_name, true),
    threadLastReply: on(config.thread_last_reply, true),
    threadRankCard: on(config.thread_rank_card, true),
    hotFavoriteCard: on(config.hot_favorite_card, false),
    hotFavoriteCount: Math.min(
      50,
      Math.max(1, Math.floor(Number(config.hot_favorite_count)) || 10),
    ),
    hotFavoriteDays: Math.min(365, Math.max(1, Math.floor(Number(config.hot_favorite_days)) || 30)),
    postLike: on(config.post_like_switch, true),
    hotLikePost: on(config.hot_like_post_switch, true),
    hotLikePostLowCount: Math.min(
      999,
      Math.max(1, Math.floor(Number(config.hot_like_post_low_count)) || 10),
    ),
    hotLikePostSize: Math.min(50, Math.max(1, Math.floor(Number(config.hot_like_post_size)) || 5)),
    hotLikeIsFirst: on(config.hot_like_isfirst, false),
    loginAnnouncement: txt(config.login_announcement),
    commentAnnouncement: txt(config.comment_announcement),
    postAnnouncement: txt(config.post_announcement),
    footerOneContent: txt(config.footer_one_content),
    footerTwoContent: txt(config.footer_two_content),
    footerContactQq: txt(config.footer_contact_qq),
    footerContactWx: txt(config.footer_contact_wx),
    footerContactEmail: txt(config.footer_contact_email),
    discPageTitle: txt(config.disc_page_title),
    postShowFloors: on(config.post_show_floors, true),
    postShowTime: on(config.post_show_time, false),
    postFuncPosition: Number(config.post_func_position) === 1 ? 1 : 0,
    threadLeftSwitch: on(config.thread_left_switch, true),
    threadTopNav: on(config.thread_top_nav, true),
    threadReplyReload: on(config.thread_reply_reload, false),
    threadSubjectSize: Math.min(
      24,
      Math.max(12, Math.floor(Number(config.thread_subject_size)) || 14),
    ),
    indexUserinfo: on(config.index_userinfo, true),
    siteInfoTotal: on(config.site_info_total, true),
    newThread: on(config.new_thread, false),
    threadFooterInfo: on(config.thread_footer_info, false),
    threadFooterInfoContent: txt(config.thread_footer_info_content),
    loginPageBanner: txt(config.login_page_banner),
    footerIconShow: on(config.footer_icon_show, true),
    themeCopyrightSwitch: on(config.theme_copyright_switch, true),
    navSearchForm: on(config.nav_search_form, true),
    headerGoldCount: on(config.header_gold_count, true),
    threadQuickAt: on(config.thread_quick_at, false),
    bodyFontStyle: fontN === 1 || fontN === 2 ? (fontN as 1 | 2) : 0,
    userBgSwitch: on(config.user_bg_switch, true),
    userBgNum: Math.min(20, Math.max(1, Math.floor(Number(config.user_bg_num)) || 9)),
    darkMode: on(config.dark_mode_switch, true),
    darkTime1: hour(config.dark_time_1, 19),
    darkTime2: hour(config.dark_time_2, 7),
  };
}

